-- Évolution v2 : e-mails réels obligatoires.
--  * CODE_EMAIL : codes à 6 chiffres envoyés par e-mail, pour confirmer l'adresse à l'inscription
--    (VERIFICATION) ou pour changer un mot de passe oublié (REINITIALISATION). Le code est stocké haché.
--  * UTILISATEUR.EMAIL_VERIFIE : un compte ne peut pas se connecter tant que son e-mail n'est pas confirmé.
--  * Suppression des comptes de démonstration aux adresses fictives (@smartbuy.tn).
CREATE TABLE code_email (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    utilisateur_id  NUMBER         NOT NULL,
    but             VARCHAR2(20)   NOT NULL,
    code_hache      VARCHAR2(100)  NOT NULL,
    expiration      TIMESTAMP      NOT NULL,
    tentatives      NUMBER(2)      DEFAULT 0 NOT NULL,
    utilise         CHAR(1)        DEFAULT 'N' NOT NULL,
    date_creation   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_code_email PRIMARY KEY (id),
    CONSTRAINT ck_code_email_but CHECK (but IN ('VERIFICATION', 'REINITIALISATION')),
    CONSTRAINT ck_code_email_utilise CHECK (utilise IN ('O', 'N')),
    CONSTRAINT fk_code_email_utilisateur FOREIGN KEY (utilisateur_id)
        REFERENCES utilisateur (id) ON DELETE CASCADE
);
CREATE INDEX ix_code_email_utilisateur ON code_email (utilisateur_id, but);

ALTER TABLE utilisateur ADD (email_verifie CHAR(1) DEFAULT 'N' NOT NULL);
ALTER TABLE utilisateur ADD CONSTRAINT ck_utilisateur_email_verifie CHECK (email_verifie IN ('O', 'N'));

