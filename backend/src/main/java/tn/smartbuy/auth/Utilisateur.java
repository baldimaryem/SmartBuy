package tn.smartbuy.auth;

import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import tn.smartbuy.commun.OuiNonConverter;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/** Table UTILISATEUR : un compte de l'application. */
@Entity
@Table(name = "UTILISATEUR")
public class Utilisateur {

    /** IDENTITY : c'est Oracle qui numérote (colonne GENERATED BY DEFAULT AS IDENTITY). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "NOM", nullable = false)
    private String nom;

    @Column(name = "EMAIL", nullable = false, unique = true)
    private String email;

    /** Jamais le mot de passe en clair : seulement son empreinte BCrypt. */
    @Column(name = "MOT_DE_PASSE_HACHE", nullable = false)
    private String motDePasseHache;

    @Enumerated(EnumType.STRING)
    @Column(name = "ROLE", nullable = false)
    private Role role = Role.USER;

    @Column(name = "DEVISE", nullable = false)
    private String devise = "TND";

    @Column(name = "REVENU_MENSUEL")
    private BigDecimal revenuMensuel;

    @Column(name = "DATE_CREATION", nullable = false)
    private LocalDateTime dateCreation = LocalDateTime.now();

    /** L'adresse a été confirmée avec le code reçu par e-mail : sans cela, pas de connexion. */
    @Convert(converter = OuiNonConverter.class)
    @Column(name = "EMAIL_VERIFIE", nullable = false)
    private boolean emailVerifie;

    public boolean isEmailVerifie() {
        return emailVerifie;
    }

    public void setEmailVerifie(boolean emailVerifie) {
        this.emailVerifie = emailVerifie;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getNom() {
        return nom;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getMotDePasseHache() {
        return motDePasseHache;
    }

    public void setMotDePasseHache(String motDePasseHache) {
        this.motDePasseHache = motDePasseHache;
    }

    public Role getRole() {
        return role;
    }

    public void setRole(Role role) {
        this.role = role;
    }

    public String getDevise() {
        return devise;
    }

    public void setDevise(String devise) {
        this.devise = devise;
    }

    public BigDecimal getRevenuMensuel() {
        return revenuMensuel;
    }

    public void setRevenuMensuel(BigDecimal revenuMensuel) {
        this.revenuMensuel = revenuMensuel;
    }

    public LocalDateTime getDateCreation() {
        return dateCreation;
    }

    public void setDateCreation(LocalDateTime dateCreation) {
        this.dateCreation = dateCreation;
    }
}
